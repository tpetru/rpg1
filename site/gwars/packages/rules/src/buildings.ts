export type BuildingId = (typeof BUILDING_IDS)[number];
export type BuildingLevels = Record<BuildingId, number>;

export interface BuildingDef {
  id: BuildingId;
  name: string;
  description: string;
  maxLevel: number;
  /** Cost of level 1; level n costs baseCost * costFactor^(n-1). */
  baseCost: ResourceBag;
  costFactor: number;
  /** Seconds for level 1 at world speed 1 with City Hall level 0. */
  baseTime: number;
  timeFactor: number;
  /** Total population used at level 1; level n uses basePop * popFactor^(n-1) in total. */
  basePop: number;
  popFactor: number;
  /** Points for level 1; every next level is worth 1.2x the previous one. */
  basePoints: number;
  /** Built levels of other buildings required before this one can be queued. */
  requires: Partial<BuildingLevels>;
  produces?: Resource;
}

